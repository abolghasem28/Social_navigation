def parse_survey_columns(question_str):
    """Extracts the Base Scene, Pair, and Framing from the raw survey header."""
    match = re.search(r'^([A-Za-z0-9]+)\[.*?\[\[(.*?)\].*?(walking|robot)', question_str)
    if not match:
        return None, None, None
    
    scene_raw = match.group(1)
    pair = f"[{match.group(2).replace(' ', '')}]"
    framing_type = match.group(3)
    
    framing = 'Human' if framing_type == 'walking' else 'Robot'
    return scene_raw, pair, framing

def load_and_format_survey_data(csv_path):
    """Processes survey data, preserving individual responses for distribution plots."""
    df = pd.read_csv(csv_path)
    last_page_col = 'lastpage. Last page'
    max_page = df[last_page_col].max() #
    df = df[df[last_page_col] == max_page].copy()  # Keep only completed responses (those that reached the last page)
    print(f"Using {len(df)} completed survey responses (last page = {max_page})")
    
    # Drop irrelevant metadata
    meta_cols = ['id. Response ID', 'submitdate. Date submitted', 'lastpage. Last page', 
                 'startlanguage. Start language', 'seed. Seed', 'startdate. Date started', 
                 'datestamp. Date last action', 'Q00. {rand(1,2)}']
    df_responses = df.drop(columns=[c for c in meta_cols if c in df.columns])
    
    # Melt to long format
    df_long = df_responses.melt(var_name='Question', value_name='Response').dropna(subset=['Response'])
    
    # Map Likert scale
    rating_map = {
        'Strongly Disagree': 0.0,
        'Disagree': 0.25,
        'Neutral': 0.5,
        'Agree': 0.75,
        'Strongly Agree': 1.0
    }
    df_long['Score'] = df_long['Response'].map(rating_map)
    
    # Parse attributes
    df_long[['Scene_Raw', 'Pair', 'Evaluator']] = df_long['Question'].apply(lambda x: pd.Series(parse_survey_columns(x)))
    df_long = df_long.dropna(subset=['Scene_Raw'])
    
    # Normalize Scene nomenclature (Strip 'R' prefix for Robot framing)
    df_long['Base_Scene'] = df_long.apply(
        lambda row: row['Scene_Raw'][1:] if row['Evaluator'] == 'Robot' and row['Scene_Raw'].startswith('R') else row['Scene_Raw'], 
        axis=1
    )

    human_cols = [c for c in df.columns if re.search(r'walking',c) ]
    robot_cols = [c for c in df.columns if re.search(r'robot',c) ]
    n_human_participants = int(df[human_cols].notna().any(axis=1).sum())
    n_robot_participants = int(df[robot_cols].notna().any(axis=1).sum())

    # Keep only what we need for the plot
    return df_long[['Base_Scene', 'Pair', 'Evaluator', 'Score']], n_human_participants, n_robot_participants

def load_and_format_vlm_data(csv_path, vlm_label):
    """Formats VLM prediction data to match the survey structure."""
    df_vlm = pd.read_csv(csv_path)

    
    # Remove errors and standardize Image Type
    df_clean = df_vlm[df_vlm['Image_Type'] != 'ERROR'].copy()
    df_clean['Image_Type'] = df_clean['Image_Type'].astype(str).str.strip().str.title()
    
    # Ensure Score is numeric
    df_clean['Score'] = pd.to_numeric(df_clean['Predicted_Crossability'], errors='coerce')
    df_clean = df_clean.dropna(subset=['Score'])
    
    # Clean Strings
    df_clean['Pair'] = df_clean['Pair'].astype(str).str.replace(' ', '').str.replace("'", "").str.replace('"', "")
    
    # Extract Base Scene (Strip suffixes)
    df_clean['Base_Scene'] = df_clean['Filename'].astype(str).apply(
        lambda x: x.replace('_raw.jpg', '').replace('_annotated.jpg', '').replace('_depth.png', '')
    )
    
    # Rename Image_Type to 'Evaluator' to align with survey data (e.g., "VLM Raw")
    df_clean['Evaluator'] = vlm_label + ' ' + df_clean['Image_Type']
    
    return df_clean[['Base_Scene', 'Pair', 'Evaluator', 'Score']]


