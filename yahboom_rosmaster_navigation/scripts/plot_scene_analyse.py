def generate_statistical_analysis(output_path):
    # Load complete survey only
    df_raw = pd.read_csv(SURVEY_CSV)
    df_raw.columns = df_raw.columns.str.strip()
    max_page = df_raw['lastpage. Last page'].max()
    df_raw = df_raw[df_raw['lastpage. Last page'] == max_page].copy()

    likert = {'Strongly Disagree':0.0,'Disagree':0.25,'Neutral':0.5,
              'Agree':0.75,'Strongly Agree':1.0}
    records = []
    for col in df_raw.columns:
        m = re.match(r'^(R?)([A-Za-z0-9]+)\[SQ\d+\]\.\s+\[\[(\d+)[,\s]+(\d+)\]', col)
        if not m: continue
        scene, pair = m.group(2), f"[{m.group(3)},{m.group(4)}]"
        src = 'Robot' if m.group(1)=='R' else 'Human'
        for resp_idx, val in df_raw[col].dropna().items():
            if val in likert:
                records.append({'Respondent':resp_idx,'Scene':scene,
                                'Pair':pair,'Framing':src,'Score':likert[val]})
    survey = pd.DataFrame(records)
    survey['Scene_Pair'] = survey['Scene'] + '_' + survey['Pair']

    # ── Mixed ANOVA ───────────────────────────────────────────────────────────
    aov = pg.mixed_anova(data=survey, dv='Score', within='Scene_Pair',
                         between='Framing', subject='Respondent')
    aov_framing = aov[aov['Source']=='Framing'].iloc[0]
    aov_within  = aov[aov['Source']=='Scene_Pair'].iloc[0]
    aov_inter   = aov[aov['Source']=='Interaction'].iloc[0]

    print(f"Mixed ANOVA — Framing:     F={aov_framing['F']:.3f}, p={aov_framing['p_unc']:.4f}, η²={aov_framing['np2']:.3f}")
    print(f"Mixed ANOVA — Scene_Pair:  F={aov_within['F']:.3f}, p={aov_within['p_unc']:.2e}, η²={aov_within['np2']:.3f}")
    print(f"Mixed ANOVA — Interaction: F={aov_inter['F']:.3f}, p={aov_inter['p_unc']:.4f}")

    # ── T-test on spread per pair ─────────────────────────────────────────────
    std_per_pair = survey.groupby(['Scene','Pair','Framing'])['Score'].std().reset_index()
    std_per_pair.columns = ['Scene','Pair','Framing','Std']
    human_std = std_per_pair[std_per_pair['Framing']=='Human'].set_index(['Scene','Pair'])['Std']
    robot_std = std_per_pair[std_per_pair['Framing']=='Robot'].set_index(['Scene','Pair'])['Std']
    common = human_std.index.intersection(robot_std.index)
    h_std = human_std.loc[common].values
    r_std = robot_std.loc[common].values
    t_stat, p_ttest = stats.ttest_rel(h_std, r_std)
    #w_stat, p_wilcox = stats.wilcoxon(h_std, r_std)

    print(f"T-test: Human std μ={h_std.mean():.3f}, Robot std μ={r_std.mean():.3f}, t={t_stat:.3f}, p={p_ttest:.4f}")
    #print(f"Wilcoxon: W={w_stat:.0f}, p={p_wilcox:.4f}")

    # ── FIGURE ────────────────────────────────────────────────────────────────
    palette = {'Human':'#4169E1','Robot':'#FF8C00'}

    def fmt_p(p):
        if p < 0.001: return 'p < 0.001 (***)'
        elif p < 0.01: return f'p = {p:.3f} (**)'
        elif p < 0.05: return f'p = {p:.3f} (*)'
        else: return f'p = {p:.3f} (n.s.)'

    fig, axes = plt.subplots(1, 2, figsize=(16, 7))
    fig.patch.set_facecolor('white')

    # ── Panel A — Interaction plot ────────────────────────────────────────────
    ax = axes[0]
    means = survey.groupby(['Framing','Scene'])['Score'].mean().reset_index()
    scene_order = sorted(means['Scene'].unique())

    for framing, color in palette.items():
        grp = means[means['Framing']==framing].set_index('Scene').reindex(scene_order)
        mu = survey[survey['Framing']==framing]['Score'].mean()
        ax.scatter(range(len(scene_order)), grp['Score'],
                   color=color, s=80, zorder=3,
                   alpha=0.9, label=f'{framing} (μ={mu:.3f})')

    for i, scene in enumerate(scene_order):
        h = means[(means['Framing']=='Human') & (means['Scene']==scene)]['Score'].values
        r = means[(means['Framing']=='Robot') & (means['Scene']==scene)]['Score'].values
        if len(h) and len(r):
            ax.plot([i,i],[r[0],h[0]], color='gray', linewidth=1,
                    alpha=0.4, linestyle='-', zorder=1)

    ax.set_facecolor('#F8F8F8')
    ax.yaxis.grid(True, linestyle='--', alpha=0.4, linewidth=0.6)
    ax.set_axisbelow(True)
    ax.set_xticks(range(len(scene_order)))
    ax.set_xticklabels([re.sub(r'\d+','',s)+'\n'+s[-4:] for s in scene_order],
                       rotation=30, ha='right', fontsize=8.5)
    ax.set_ylabel('Mean Crossability Score', fontsize=12)
    ax.set_ylim(0, 1.1)
    ax.set_yticks([0, 0.25, 0.5, 0.75, 1.0])
    ax.legend(fontsize=11, loc='upper right')
    ax.set_title('A — Mixed ANOVA\nMean Crossability per Scene by Framing',
                 fontsize=12, fontweight='bold')

    textstr = (
        f"Framing (between):  F={aov_framing['F']:.2f}, {fmt_p(aov_framing['p_unc'])}, η²={aov_framing['np2']:.3f}\n"
        f"Scene (within):     F={aov_within['F']:.2f}, {fmt_p(aov_within['p_unc'])}, η²={aov_within['np2']:.3f}\n"
        f"Interaction:        F={aov_inter['F']:.2f}, {fmt_p(aov_inter['p_unc'])}, η²={aov_inter['np2']:.3f}"
    )
    ax.text(0.01, 0.02, textstr, transform=ax.transAxes, fontsize=9,
            verticalalignment='bottom', fontfamily='monospace',
            bbox=dict(boxstyle='round', facecolor='white', alpha=0.9))

    # ── Panel B — T-test on spread ────────────────────────────────────────────
    ax2 = axes[1]
    std_long = pd.DataFrame({'Human':h_std,'Robot':r_std}).melt(
        var_name='Framing', value_name='Std')

    sns.violinplot(data=std_long, x='Framing', y='Std',
                   hue='Framing', palette=palette, inner=None, cut=0,
                   linewidth=1.5, ax=ax2, order=['Human','Robot'],
                   alpha=0.45, legend=False)
    sns.swarmplot(data=std_long, x='Framing', y='Std',
                  hue='Framing', palette=palette, order=['Human','Robot'],
                  size=4.5, alpha=0.85, edgecolor='black', linewidth=0.3,
                  ax=ax2, legend=False, warn_thresh=1.0)

    for i, (framing, color) in enumerate(palette.items()):
        m = h_std.mean() if framing=='Human' else r_std.mean()
        ax2.hlines(m, i-0.3, i+0.3, colors=color, linewidth=3.5,
                   linestyles='solid', zorder=6)
        ax2.text(i+0.33, m, f'μ={m:.3f}', va='center', fontsize=11,
                 color=color, fontweight='bold')

    y_top = max(h_std.max(), r_std.max()) + 0.03
    ax2.plot([0,0,1,1],[y_top,y_top+0.02,y_top+0.02,y_top],
             color='black', lw=1.2)
    sig = '***' if p_ttest<0.001 else ('**' if p_ttest<0.01 else ('*' if p_ttest<0.05 else 'n.s.'))
    ax2.text(0.5, y_top+0.02,
             f'Paired t-test: t={t_stat:.2f}, p={p_ttest:.4f} ({sig})',
             ha='center', fontsize=11, fontweight='bold')
    # ax2.text(0.5, y_top+0.00,
    #          f'Wilcoxon: W={w_stat:.0f}, p={p_wilcox:.4f}',
    #          ha='center', fontsize=9, color='gray')

    ax2.set_facecolor('#F8F8F8')
    ax2.yaxis.grid(True, linestyle='--', alpha=0.4, linewidth=0.6)
    ax2.set_axisbelow(True)
    ax2.set_ylabel('Standard Deviation of Crossability Ratings\n(per scene/pair)', fontsize=12)
    ax2.set_xlabel('Framing Condition', fontsize=12)
    ax2.set_title('B — T-test on Rating Spread\nConsensus: Human vs Robot Framing per Pair',
                  fontsize=12, fontweight='bold')
    ax2.text(0.5, -0.06, f'N = {len(h_std)} scene/pair combinations  |  α = 0.05',
             ha='center', transform=ax2.transAxes,
             fontsize=9, color='gray', style='italic')

    fig.suptitle('Statistical Analysis — Mixed ANOVA & Consensus Comparison\n'
                 '(24 complete respondents, between-subjects design, α = 0.05)',
                 fontsize=13, fontweight='bold')
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
