def generate_composed_plot():
    print("Loading Survey Baseline Data...")
    #df_list = [load_and_format_survey_data(SURVEY_CSV)]
    
    survey_df, n_human_p, n_robot_p = load_and_format_survey_data(SURVEY_CSV)
    df_list = [survey_df]

    print("Loading VLM Prompt Data...")
    for prompt_label, csv_path in VLM_CSVS.items():
        if os.path.exists(csv_path):
            print(f" -> Found data for {prompt_label}")
            df_list.append(load_and_format_vlm_data(csv_path, prompt_label))
        else:
            print(f" -> WARNING: Could not find {csv_path}. Skipping.")
            
    df_master = pd.concat(df_list, ignore_index=True)
    
    unique_scenes = sorted(df_master['Base_Scene'].unique())
    num_scenes = len(unique_scenes)
    
    # 1. Dynamic Grid Calculation
    cols = 4
    rows = math.ceil(num_scenes / cols)
    
    # INCREASED FIGSIZE to handle 10 bars per pair
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 8, rows * 6))
    if num_scenes == 1: axes = [axes] # Handle single plot edge case
    else: axes = axes.flatten()
    
    # 2. Define the Expanded Color Palette
    # Strategy: Human/Robot are distinct. Prompts use Light (Raw) / Dark (Annotated) pairs.
    palette_colors = {
            'Human':              '#1f77b4',   # Strong Blue
            'Robot':              '#ff7f0e',   # Strong Orange

            'Prompt A Raw':       '#e31a1c',   # Strong Red
            'Prompt A Annotated': '#fb9a99',   # Light Red (clearly same family)

            'Prompt B Raw':       '#33a02c',   # Strong Green
            'Prompt B Annotated': '#b2df8a',   # Light Green

            'Prompt C Raw':       '#6a3d9a',   # Strong Purple
            'Prompt C Annotated': '#cab2d6',   # Light Purple

            'Prompt D Raw':       '#b8860b',   # Strong Gold/Dark Yellow
            'Prompt D Annotated': '#ffd700',   # Bright Yellow
                }
    
    # Filter the order to only include data we actually successfully loaded
    loaded_evaluators = df_master['Evaluator'].unique()
    evaluator_order = [e for e in palette_colors.keys() if e in loaded_evaluators]
    
    # 3. Plotting Loop
    for i, scene in enumerate(unique_scenes):
        ax = axes[i]
        df_scene = df_master[df_master['Base_Scene'] == scene].copy()
        
        # Sort numeric pairs correctly
        df_scene['Pair_Sort'] = df_scene['Pair'].apply(lambda x: [int(num) for num in re.findall(r'\d+', x)])
        df_scene = df_scene.sort_values(by='Pair_Sort')
        


        # Plot Boxes
        sns.boxplot(
            data=df_scene, x='Pair', y='Score', 
            hue='Evaluator', hue_order=evaluator_order, 
            palette=palette_colors, showfliers=False, 
            boxprops=dict(alpha=0.3),  
            zorder=1, linewidth=1.2, ax=ax
        )
        
        # 2. THE STRIPPLOT (The Foreground Layer)
        # dodge=True ensures the dots align perfectly over their respective boxes.
        # zorder=2 forces the dots to physically draw on top of the boxes.
        # linewidth=0.3 and edgecolor='black' puts a tiny ring around each dot so they pop!
        sns.swarmplot(
            data=df_scene, x='Pair', y='Score',
            hue='Evaluator', hue_order=evaluator_order,
            palette=palette_colors, dodge=True,
            size=3.5, alpha=0.9, zorder=2,
            edgecolor='black', linewidth=0.3,
            ax=ax, legend=False,
            warn_thresh=1.0  # suppress overlap warnings
        )
        
        # Subplot specific formatting
        ax.set_title(f'Scene: {scene}', fontsize=16, fontweight='bold', pad=10)
        ax.set_facecolor('#F8F8F8')
        ax.yaxis.grid(True, linestyle='--', alpha=0.5, linewidth=0.6, color='gray')
        ax.set_axisbelow(True)
        ax.set_ylim(-0.05, 1.05)
        ax.set_xlabel('Interacting Pair (IDs)' if i >= num_scenes - cols else '', fontsize=12)
        ax.set_ylabel('Crossability Probability' if i % cols == 0 else '', fontsize=12)
        
        # Remove individual legends
        if ax.get_legend() is not None:
            ax.get_legend().remove()

        fig_single, ax_single = plt.subplots(figsize=(12, 5))
        def_scene_sorted = df_scene.sort_values(by='Pair_Sort')
        sns.boxplot( data=def_scene_sorted, x='Pair', y='Score', 
            hue='Evaluator', hue_order=evaluator_order, 
            palette=palette_colors, showfliers=False, 
            boxprops=dict(alpha=0.3),  
            zorder=1, linewidth=1.2, ax=ax_single, legend=False )
        sns.stripplot( data=def_scene_sorted, x='Pair', y='Score',
            hue='Evaluator', hue_order=evaluator_order,
            palette=palette_colors, dodge=True, jitter=0.2,
            size=3.5, alpha=0.9, zorder=2,
            edgecolor='black', linewidth=0.3,
            ax=ax_single, legend=False )
        
        ax_single.set_facecolor('#F8F8F8')
        ax_single.yaxis.grid(True, linestyle='--', alpha=0.5, linewidth=0.6)
        ax_single.set_axisbelow(True)
        ax_single.set_ylim(-0.05, 1.05)
        ax_single.set_title(f'Scene: {scene}', fontsize=16, fontweight='bold')
        ax_single.set_xlabel('Interacting Pair (IDs)', fontsize=12)
        ax_single.set_ylabel('Crossability Probability', fontsize=12)
        handles = [plt.scatter([], [], color=palette_colors[eval], s=40, label=eval) for eval in evaluator_order]
        fig_single.legend(handles=handles, labels=evaluator_order, title='Evaluation Source', loc='upper center', bbox_to_anchor=(1.05, 1), borderaxespad=0, fontsize=9, title_fontsize=10, frameon=True)
        fig_single.tight_layout()
        fig_single.savefig(os.path.join(OUTPUT_INDIVIDUAL_PLOT_DIR, f'{scene}_crossability_analysis.png'), dpi=300, bbox_inches='tight')
        plt.close(fig_single)
    print(f"---> Individual scene plots saved to: {OUTPUT_INDIVIDUAL_PLOT_DIR}")
    
    # Clean up empty subplots
    for j in range(i + 1, len(axes)):
        fig.delaxes(axes[j])

    # 4. Global Legend (Forced into 5 columns so it stacks neatly in 2 rows at the top)
    handles, labels = axes[0].get_legend_handles_labels()
    
    # Filter handles to match the evaluator order
    legend_dict = dict(zip(labels, handles))
    ordered_handles = [legend_dict[lbl] for lbl in evaluator_order if lbl in legend_dict]
    
    fig.legend(ordered_handles, evaluator_order, title='Evaluation Source', loc='lower center', 
           bbox_to_anchor=(0.5, 0.0), ncol=5, fontsize=12, title_fontsize=14)
    plt.tight_layout(rect=[0, 0.08, 1, 1])  # Leave space at the top for the legend

    plt.savefig(OUTPUT_PLOT_FILE, dpi=300, bbox_inches='tight')

    plt.close()

    generate_violin_plot(df_master, OUTPUT_VIOLIN_FILE, n_human_p, n_robot_p)

    generate_gt_comparison_plot(df_master, GT_CSV, OUT_GT_FILE)
    generate_statistical_analysis(OUTPUT_STATS_FILE)

    print(f"---> Master composed plot saved to: {OUTPUT_PLOT_FILE}")

